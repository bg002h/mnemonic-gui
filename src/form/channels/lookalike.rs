/// Full case folding, as `str.casefold()`: the table above, else the full
/// lowercase mapping.
fn casefold(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match CASEFOLD_NOT_LOWER.binary_search_by(|(k, _)| k.cmp(&c)) {
            Ok(i) => out.push_str(CASEFOLD_NOT_LOWER[i].1),
            Err(_) => out.extend(c.to_lowercase()),
        }
    }
    out
}

/// `channel_policy.json` `channel_lookalike.normalize`.
pub fn normalize_for_lookalike(v: &str) -> String {
    let nfkc: String = v.nfkc().collect();
    let kept: String = nfkc.chars().filter(|&c| !is_cc(c) && !is_cf(c)).collect();
    casefold(kept.trim())
}

/// R4 NI8: could this value be read as a channel under any plausible
/// normalization? Refused on every path (`value-looks-like-a-channel`).
pub fn looks_like_channel(policy: &Policy, v: &str) -> bool {
    let n = normalize_for_lookalike(v);
    let rule = &policy.channel_lookalike;
    rule.refuse_if_equals.contains(&n)
        || rule
            .refuse_if_startswith
            .iter()
            .any(|p| n.starts_with(p.as_str()))
}

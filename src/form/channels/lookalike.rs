//! R4 NI8 — the channel-lookalike predicate, a DECISION (DESIGN §A0.1).
//!
//! A resolved or typed secret is normalized: NFKC, drop Unicode categories Cc
//! and Cf (controls, NUL, zero-width and other format characters), strip
//! Unicode whitespace, case-fold. If it then equals `-` or starts with `@env`
//! (`channel_policy.json` `channel_lookalike`), it is refused on EVERY path,
//! whatever any CLI would do with it.
//!
//! Mirrors `plan.normalize_for_lookalike` / `plan.looks_like_channel`. Python's
//! `str.strip()` and Rust's `str::trim()` agree once Cc/Cf are gone (the only
//! `isspace` characters outside `White_Space` are Cc). Case-folding is
//! `to_lowercase` plus the generated table of code points where
//! `str.casefold()` differs from `str.lower()`; the
//! exhaustive parity test (`tests/secret_channels_t1.rs`) checks the whole
//! predicate against the Python reference over every code point.

